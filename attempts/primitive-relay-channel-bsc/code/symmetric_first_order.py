import numpy as np
from mpmath import mp, mpf, log
from scipy.optimize import minimize

mp.dps = 50


def hb(x):
    x = mpf(x)
    if x <= 0 or x >= 1:
        return mpf(0)
    return -(x * log(x, 2) + (1 - x) * log(1 - x, 2))


def star(a, b):
    return a * (1 - b) + (1 - a) * b


def dkl(t, r):
    t, r = mpf(t), mpf(r)
    out = mpf(0)
    if t > 0:
        out += t * log(t / r, 2)
    if t < 1:
        out += (1 - t) * log((1 - t) / (1 - r), 2)
    return out


# ---------------------------------------------------------------- slope
def cmd_slope(rhos):
    for rho in rhos:
        rho = mpf(rho)
        k = 1 - 2 * rho
        s = k * k / (1 + k * k)
        worst = mpf(-1)
        arg = None
        for i in range(1, 2000):
            th = mpf(i) / 4000           # theta in (0, 1/2)
            num = hb(star(star(th, rho), rho)) - hb(star(th, rho))
            den = hb(star(star(th, rho), rho)) - hb(th)
            r = num / den
            if r > worst:
                worst, arg = r, th
        print(f"rho={mp.nstr(rho, 4)}  s=k^2/(1+k^2)={mp.nstr(s, 15)}  "
              f"max_grid r={mp.nstr(worst, 15)} at theta={mp.nstr(arg, 6)}  "
              f"(U=Yr ratio {mp.nstr((hb(star(rho, rho)) - hb(rho)) / hb(star(rho, rho)), 8)})")
        assert worst < s


# ---------------------------------------------------------------- EGN Theorem 6
def egn_terms(a, u, v, rho):
    """Return (Delta, E, c): f_lambda = (1-lambda)*Delta + E, c = P(X != Z)."""
    a, u, v, rho = mpf(a), mpf(u), mpf(v), mpf(rho)
    y = rho + (1 - 2 * rho) * a
    z = (1 - a) * u + a * (1 - v)
    c = (1 - a) * u + a * v
    return hb(y) - hb(z), (1 - a) * hb(u) + a * hb(v), c


def cmd_egn_pos(rho):
    rho = mpf(rho)
    hp = log((1 - rho) / rho, 2)          # h'(rho)
    for lam in ("0.5", "0.9", "0.99", "0.999", "0.9999"):
        lam = mpf(lam)
        a = mpf("0.25")
        y = rho + (1 - 2 * rho) * a
        # first-order optimal t ~ (1-lam) h'(y) / (second-order coefficient); search
        best = None
        for e in range(1, 400):
            t = mpf(e) / 4000 * (1 - lam) * 10
            if t >= rho:
                break
            D, E, c = egn_terms(a, rho - t, rho + t, rho)
            phi = (1 - lam) * D + E - (hb(rho) + hp * (c - rho))
            if best is None or phi > best[0]:
                best = (phi, t)
        print(f"lambda={mp.nstr(lam, 6)}: point (a,u,v)=(0.25, rho-t, rho+t), t={mp.nstr(best[1], 6)}, "
              f"f_lambda - [h(rho)+h'(rho)(c-rho)] = {mp.nstr(best[0], 6)} > 0: {best[0] > 0}")


def _f_float(x, rho, lam):
    a, u, v = x
    hf = lambda q: 0.0 if q <= 0 or q >= 1 else -(q * np.log2(q) + (1 - q) * np.log2(1 - q))
    y = rho + (1 - 2 * rho) * a
    z = (1 - a) * u + a * (1 - v)
    return (1 - lam) * (hf(y) - hf(z)) + (1 - a) * hf(u) + a * hf(v)


def _best_config(rho, lam, rng, tries=40):
    """Find (P, t) maximizing w f(P) + (1-w) h(t) with w c(P) + (1-w) t = rho."""
    hf = lambda q: 0.0 if q <= 0 or q >= 1 else -(q * np.log2(q) + (1 - q) * np.log2(1 - q))
    best = (-1e9, None)

    def neg(x):
        a, u, v, t = np.clip(x, 1e-9, 1 - 1e-9)
        c = (1 - a) * u + a * v
        if abs(c - t) < 1e-12:
            return 1e3
        w = (rho - t) / (c - t)
        if not (0 <= w <= 1):
            return 1e3 + abs(w)
        return -(w * _f_float((a, u, v), rho, lam) + (1 - w) * hf(t))
    for _ in range(tries):
        x0 = rng.uniform(0.01, 0.99, 4)
        r = minimize(neg, x0, method="Nelder-Mead",
                     options={"xatol": 1e-11, "fatol": 1e-14, "maxiter": 6000})
        if -r.fun > best[0]:
            best = (-r.fun, np.clip(r.x, 1e-9, 1 - 1e-9))
    return best


def cmd_egn_low(rho, R0s):
    rng = np.random.default_rng(7)
    rho_f = float(rho)
    rho = mpf(rho)
    # Affine pieces alpha + beta*lambda lower-bounding Env g_lambda(rho).
    pieces = [(hb(rho), mpf(0))]           # symmetric point: Env >= h(rho)
    for lam in list(np.linspace(0.0, 0.95, 20)) + list(1 - np.logspace(-1.3, -4, 25)):
        val, x = _best_config(rho_f, float(lam), rng)
        if x is None:
            continue
        a, u, v, t = (mpf(repr(float(q))) for q in x)
        D, E, c = egn_terms(a, u, v, rho)
        w = (rho - t) / (c - t)
        if not (0 <= w <= 1):
            continue
        # w[(1-lam) D + E] + (1-w) h(t) = [w(D+E) + (1-w)h(t)] - w D lam
        pieces.append((w * (D + E) + (1 - w) * hb(t), -w * D))
    print(f"{len(pieces)} affine lower pieces for Env g_lambda(rho) at rho={mp.nstr(rho, 4)}")
    base = 1 - 2 * hb(rho)
    for R0 in R0s:
        R0 = mpf(R0)
        lines = [(base + al, be + R0) for al, be in pieces]     # value = A + B*lambda
        cand = {mpf(0), mpf(1)}
        for (A1, B1), (A2, B2) in combinations(lines, 2):
            if B1 != B2:
                x = (A2 - A1) / (B1 - B2)
                if 0 < x < 1:
                    cand.add(x)
        lower = min(max(A + B * x for A, B in lines) for x in cand)
        cutset = min(1 - hb(rho) + R0, 1 + hb(star(rho, rho)) - 2 * hb(rho))
        print(f"R0={mp.nstr(R0, 4)}: EGN-Thm6 bound >= {mp.nstr(lower, 10)}   "
              f"cutset = {mp.nstr(cutset, 10)}   cutset - lower <= {mp.nstr(cutset - lower, 6)}")


# ---------------------------------------------------------------- BSC curve
def cmd_bsc_curve(rhos):
    for rho in rhos:
        rho = mpf(rho)
        ths = [mpf(i) / 2000 for i in range(1, 1000)]
        pts = []
        for th in ths:
            b = hb(star(star(th, rho), rho)) - hb(th)
            a = hb(star(star(th, rho), rho)) - hb(star(th, rho))
            pts.append((b, a))
        # as theta increases, b decreases; slopes da/db along consecutive points
        slopes = [(pts[i + 1][1] - pts[i][1]) / (pts[i + 1][0] - pts[i][0]) for i in range(len(pts) - 1)]
        mono = all(slopes[i + 1] >= slopes[i] for i in range(len(slopes) - 1))
        print(f"rho={mp.nstr(rho, 4)}: chord slopes increasing along theta (concave curve): {mono}; "
              f"slope range [{mp.nstr(slopes[0], 6)}, {mp.nstr(slopes[-1], 6)}], "
              f"s={mp.nstr((1 - 2 * rho) ** 2 / (1 + (1 - 2 * rho) ** 2), 6)}")


# ---------------------------------------------------------------- uniform input
def cmd_unif(rhos):
    sys.path.insert(0, __file__.rsplit("/", 1)[0])
    import cf_dual
    worst = -1.0
    for rho in rhos:
        Rmax = float(hb(star(mpf(rho), mpf(rho))))
        for R in np.linspace(0.02, 0.98, 7) * Rmax:
            u = cf_dual.cf_rate(0.5, rho, rho, R)
            best = max((cf_dual.cf_rate(pi, rho, rho, R), pi) for pi in np.arange(0.02, 0.5, 0.02))
            loc, pi_loc = cf_dual.cf_rate_opt(rho, rho, R)
            worst = max(worst, best[0] - u, loc - u)
            print(f"rho={rho} R0={R:.4f} CF(unif)={u:.7f} best grid pi<0.5: {best[0]:.7f} "
                  f"(pi={best[1]:.2f}); local opt pi*={pi_loc:.4f}", flush=True)
    print(f"max over grid of CF(pi) - CF(1/2) = {worst:.3e}")


def cmd_spi(rho):
    sys.path.insert(0, __file__.rsplit("/", 1)[0])
    import cf_dual
    from scipy.optimize import brentq

    def s_pi(pi):
        A, B, tb = cf_dual.cond_entropies(pi, rho, rho, cf_dual.THETA)
        A0, B0, _ = cf_dual.cond_entropies(pi, rho, rho, np.array([tb]))
        a, b = A0[0] - A, B0[0] - B
        # smallest s with Env_{tb}(a - s b) = 0 (the envelope is >= 0 always)
        return brentq(lambda s: cf_dual._envelope_at(a - s * b, tb) - 1e-12, 0.0, 1.0, xtol=1e-10)
    k = 1 - 2 * rho
    print(f"rho={rho}: closed form s_(1/2) = {k * k / (1 + k * k):.6f}")
    for pi in (0.5, 0.45, 0.4, 0.3, 0.2, 0.1, 0.05, 0.01):
        print(f"  pi={pi}: s_pi = {s_pi(pi):.6f}")


